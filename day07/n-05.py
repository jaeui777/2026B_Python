# Python NumPy 조별과제 - 고혈압 건강검진 데이터 분석

# 1. 데이터 준비 및 구조 (Columns)
# - 데이터 출처 : 공공데이터포털 '국민건강보험공단_직역별 성별 연령별 건강검진정보'
# - 파일명 : 국민건강보험공단_직역별 성별 연령별 건강검진정보_20231231.csv (day07 폴더)
# - 사용하는 컬럼 (총 34개 열 중)
# [0]  검진사업년도
# [4]  대상인원             : 검진을 받아야 하는 사람 수
# [5]  수검인원             : 실제로 검진을 받은 사람 수
# [27] 고혈압질환의심       : 이번 검진에서 고혈압 의심 판정을 받은 사람 수
# ※ 직역·연령·성별은 글자라서 숫자로 읽으면 사라짐 → 엑셀 줄 번호를 집단 ID로 사용

import numpy as np

데이터 = np.genfromtxt('./day07/국민건강보험공단_직역별 성별 연령별 건강검진정보_20231231.csv',delimiter=',', skip_header=1, encoding='cp949')
데이터 = np.nan_to_num(데이터)          # 빈칸 → 0
줄번호 = np.arange(len(데이터)) + 2     # 엑셀 줄 번호를 집단 ID로 사용

# 2023년 데이터 중 수검인원 1000명 이상인 집단만 사용
조건 = (데이터[:, 0] == 2023) & (데이터[:, 5] >= 1000)
데이터 = 데이터[조건]
줄번호 = 줄번호[조건]
print(f"분석 데이터 형태: {데이터.shape}")


# [Step 1] 고혈압 질환 의심 인원 현황 분석
# - 2023년 집단별 고혈압 질환 의심 인원의 평균값과 최댓값을 구하세요.

의심인원 = 데이터[:, 27]
print("평균 고혈압 질환 의심 인원:", np.mean(의심인원))
print("최대 고혈압 질환 의심 인원:", np.max(의심인원))
print("최댓값 집단 ID(엑셀 줄):", 줄번호[np.argmax(의심인원)])


# [Step 2] 고혈압 우선관리 집단 선별
# - 고혈압 질환 의심률(의심 인원 / 수검인원 * 100)을 계산하세요.
# - 조건: '의심률이 평균 이상' 이거나(|) '의심 인원이 평균 이상'인 집단을 우선관리 집단으로 분류하세요.

의심률 = 데이터[:, 27] / 데이터[:, 5] * 100
print("의심률 평균:", np.mean(의심률), "%")
print("의심 인원 평균:", np.mean(의심인원), "명")
우선관리조건 = (의심률 >= np.mean(의심률)) | (의심인원 >= np.mean(의심인원))
우선관리집단 = 줄번호[우선관리조건]
print("우선관리 집단 ID:", 우선관리집단)
print("우선관리 집단 수:", len(우선관리집단))


# [Step 3] 집단별 고혈압 집중 관리 지수 분석
# - 고혈압 질환 의심 인원 / 수검인원 으로 집중 관리 지수를 산출하고, 가장 높은 집단을 찾으세요.

관리지수 = 데이터[:, 27] / 데이터[:, 5]
관리지수높은집단 = np.argmax(관리지수)
print("지수가 가장 높은 집단 ID:", 줄번호[관리지수높은집단], "/ 지수:", 관리지수[관리지수높은집단])


# [Step 4] 복합 취약 집단 분석
# - 건강검진 참여율(수검인원 / 대상인원 * 100)을 계산하세요.
# - 조건: '의심률 10% 이상' 이면서(&) '참여율 70% 미만'인 집단을 복합 취약 집단으로 분류하세요.
# - 전체 집단 중 몇 %인지 출력하세요.

참여율 = 데이터[:, 5] / 데이터[:, 4] * 100
취약조건 = (의심률 >= 10) & (참여율 < 70)
취약집단 = 데이터[취약조건]
취약집단번호 = 줄번호[취약조건]
print("복합 취약 집단 ID:", 취약집단번호)
print("복합 취약 집단 수:", len(취약집단))
print("전체 중 비율:", len(취약집단) / len(데이터) * 100, "%")


# [Step 5] 최우선 건강검진 지원 집단 선정
# - Step 4 집단의 미수검자 수(대상인원 - 수검인원) x 고혈압 의심률 = 우선순위 지표
#   (검진을 받지 않은 사람 중 고혈압 의심자가 몇 명쯤 있을지 추정한 값)
# - 0~1 사이로 정규화(Min-Max Scaling)하고, 0.9 이상인 집단을 최우선 지원 집단으로 선정하세요.
#   * 공식 : ( x - 최솟값 ) / ( 최댓값 - 최솟값 )

미수검자 = 취약집단[:, 4] - 취약집단[:, 5]
취약의심률 = 취약집단[:, 27] / 취약집단[:, 5]
우선순위지표 = 미수검자 * 취약의심률

정규화점수 = (우선순위지표 - np.min(우선순위지표)) / (np.max(우선순위지표) - np.min(우선순위지표))
최우선조건 = 정규화점수 >= 0.9
정렬순서 = np.argsort(정규화점수)[::-1]    # 점수 높은 순

print("집단 ID(점수 높은 순):", 취약집단번호[정렬순서])
print("정규화 점수(높은 순):", 정규화점수[정렬순서])
print("최우선 지원 집단 ID:", 취약집단번호[최우선조건])
print("최우선 지원 집단 미수검자 수:", 미수검자[최우선조건])
print("숨은 고혈압 의심자 추정:", 우선순위지표[최우선조건])